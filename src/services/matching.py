# Метрика для Grafana
MATCHES_GENERATED = Counter('rex_dating_matches_total', 'Total matches generated by algorithm')

def _normalize_list(data):
    """Превращает строку 'Бег, Зал' или список ['Бег', 'Зал'] в set({'бег', 'зал'})."""
    if not data:
        return set()
    if isinstance(data, list):
        return set(str(x).lower().strip() for x in data)
    if isinstance(data, str):
        return set(x.lower().strip() for x in data.split(','))
    return set()

def _parse_int(value, default=0):
    """Безопасно извлекает число из строки (например '25 лет' -> 25)."""
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        nums = re.findall(r'\d+', value)
        if nums:
            return int(nums[0])
    return default

async def run_daily_matching():
    """
    Интеллектуальный алгоритм подбора пар.
    Срабатывает раз в сутки через scheduler.
    Учитывает город, пол, возраст и пересечение по видам спорта.
    """
    log = logger.bind(task="dating_matching")
    log.info("matching_started")
    
    try:
        async with async_session_maker() as session:
            # 1. Берем всех АКТИВНЫХ пользователей с подпиской, у которых есть анкета дейтинга
            stmt_users = select(UserSurvey).join(User).where(
                and_(
                    UserSurvey.mode == 'dating',
                    User.subscription_expires_at > func.now()
                )
            )
            result = await session.execute(stmt_users)
            seekers = result.scalars().all()
            
            log.info("profiles_fetched", count=len(seekers))
            matches_count = 0

            for me in seekers:
                try:
                    my_id = me.user_id
                    my_data = me.answers or {}
                    if my_data.get('is_paused'):
                        continue # Я скрыл анкету, не ищем мне никого
                    
                    # --- Извлекаем предпочтения Ищущего ---
                    my_city = str(my_data.get('city', '')).strip().lower()
                    my_gender = str(my_data.get('gender', '')).lower()
                    
                    # Кого ищем?
                    pref_gender = str(my_data.get('partner_gender', '')).lower()
                    if not pref_gender or 'любой' in pref_gender:
                        pref_gender = 'женский' if 'муж' in my_gender else 'мужской'

                    pref_age_min = _parse_int(my_data.get('partner_age_min'), 18)
                    pref_age_max = _parse_int(my_data.get('partner_age_max'), 99)
                    my_sports = _normalize_list(my_data.get('sports'))

                    # --- Поиск Кандидатов ---
                    # Исключаем тех, кого уже видели (лайк или дизлайк)
                    seen_stmt = select(DatingMatch.target_user_id).where(DatingMatch.user_id == my_id)
                    seen_ids = (await session.execute(seen_stmt)).scalars().all()
                    
                    # Ищем только ПОСЛЕДНЮЮ анкету для каждого пользователя
                    # (Используем подзапрос для фильтрации актуальных записей)
                    from sqlalchemy import func
                    subq_latest = select(
                        UserSurvey.user_id, 
                        func.max(UserSurvey.created_at).label('max_date')
                    ).where(UserSurvey.mode == 'dating').group_by(UserSurvey.user_id).subquery()

                    stmt_candidates = select(UserSurvey).join(
                        subq_latest, 
                        and_(
                            UserSurvey.user_id == subq_latest.c.user_id,
                            UserSurvey.created_at == subq_latest.c.max_date
                        )
                    ).join(User).where(
                        and_(
                            User.subscription_expires_at > func.now(),
                            UserSurvey.user_id != my_id,
                            UserSurvey.user_id.not_in(seen_ids) if seen_ids else True
                        )
                    ).limit(30)
                    
                    candidates = (await session.execute(stmt_candidates)).scalars().all()
                    
                    best_match = None
                    for cand in candidates:
                        cand_data = cand.answers or {}
                        
                        # 0. Проверка на паузу
                        if cand_data.get('is_paused'):
                            continue

                        # 1. Город (строгое совпадение)
                        cand_city = str(cand_data.get('city', '')).strip().lower()
                        if my_city and cand_city and my_city not in cand_city and cand_city not in my_city:
                            continue

                        # 2. ПОЛ (Исправленная логика)
                        cand_gender = str(cand_data.get('gender', '')).lower()
                        
                        # Если я ищу НЕ "любой" и пол кандидата не совпадает с моим запросом -> мимо
                        if 'любой' not in pref_gender and pref_gender not in cand_gender:
                            continue
                            
                        # ВАЖНО: Проверяем, ищет ли КАНДИДАТ меня?
                        cand_pref_gender = str(cand_data.get('partner_gender', '')).lower()
                        # Если кандидат ищет НЕ "любой" и мой пол не совпадает с его запросом -> мимо
                        if 'любой' not in cand_pref_gender and cand_pref_gender not in my_gender:
                            continue

                        # 3. ВОЗРАСТ (Диапазоны)
                        cand_age = _parse_int(cand_data.get('age'))
                        
                        # Подхожу ли я кандидату по возрасту?
                        cand_min = _parse_int(cand_data.get('partner_age_min'), 18)
                        cand_max = _parse_int(cand_data.get('partner_age_max'), 99)
                        
                        # Мой возраст (нужно достать из my_data)
                        my_age = _parse_int(my_data.get('age'))
                        
                        # Проверка: Я подхожу ЕМУ? И Он подходит МНЕ?
                        if not (pref_age_min <= cand_age <= pref_age_max):
                            continue
                        if not (cand_min <= my_age <= cand_max):
                            continue

                        # 4. СПОРТ
                        # Так как теперь спорт это кнопка (одно значение), сравниваем проще
                        # Но оставим логику set intersection на случай, если там старые данные или список
                        cand_sports = _normalize_list(cand_data.get('sports'))
                        if my_sports and cand_sports:
                            if not (my_sports & cand_sports):
                                continue

                        # Все проверки пройдены!
                        best_match = cand
                        break
                    
                    if not best_match:
                        continue

                    # --- Формирование уведомления ---
                    cand_data = best_match.answers or {}
                    info_line = f"{cand_data.get('name', 'Спортсмен')}, {cand_data.get('age', '??')}"
                    
                    sports_raw = cand_data.get('sports', '')
                    sports_str = ", ".join(sports_raw) if isinstance(sports_raw, list) else str(sports_raw)
                    level = cand_data.get('level', 'Любитель')
                    
                    caption = (
                        f"🎯 <b>Вам подобрана пара!</b>\n\n"
                        f"👤 <b>{info_line}</b>\n"
                        f"📍 {cand_data.get('city', 'Город не указан')}\n"
                        f"🏅 {sports_str} ({level})\n\n"
                        f"ℹ️ {cand_data.get('about', 'Активный пользователь REX')}"
                    )
                    
                    # Проверяем наличие фото, чтобы не было ошибки при отправке
                    photo = cand_data.get('photo')
                    log.info("match_found", 
                             my_id=my_id, 
                             candidate_id=best_match.user_id, 
                             has_photo=bool(photo),  # <--- Покажет True/False в логах
                             photo_id=photo)
                    
                    await send_to_queue("q_notifications", {
                        "user_id": my_id,
                        "text": caption,
                        "photo": photo if photo else None,
                        "keyboard": get_dating_kb(best_match.user_id).model_dump()
                    })
                    
                    MATCHES_GENERATED.inc()
                    matches_count += 1
                    
                    # Небольшая пауза, чтобы не нагружать RabbitMQ/Telegram
                    await asyncio.sleep(0.1)

                except Exception as loop_e:
                    log.error("error_processing_user", user_id=me.user_id, error=str(loop_e))
                    continue

            log.info("matching_completed", matches_created=matches_count)

    except Exception as e:
        log.error("matching_critical_failure", error=str(e))
        await send_alert(e, context="Dating Matching Service Failure")
        raise e